#!/usr/bin/env python3
"""make_names.py - Rename Day: the contract's names as files other things read.

    python3 -I LIB_ig3d/tools/make_names.py            write the three files
    python3 -I LIB_ig3d/tools/make_names.py --check    exit 1 if a file is not what the contract says today
    options: --contract PATH   --out FOLDER (default: LIB_ig3d)

Everything comes from LIB_ig3d/ENGINE_CONTRACT.md: the call, message and value tables, and the
`<!-- contract:renames -->` table (old name, new name, `same` or `signs`). Nobody edits the three
files by hand; change the contract and run this again. test_contract_check.py runs --check.

  livecode/contract_aliases.livecodescript   one thin handler for each new name whose old name is
        still the engine's own. Plain handlers, no `script` line: xt3d's tools/make_vibe_xt3d.py
        appends the file to the generated engine, and a headless test adds it after the stand-ins.
  Data/contract_words.txt                    the suggestion list's words (lib_suggest), one a line:
        kind, group, name, form, gives, xt, old name, first parameter, meaning (tabs between)
  Data/Menus/Contract.txt                    the same names as a LIB_MENU menu file (Head/Sub/Item)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import contract_check as cc                   # noqa: E402

LIB = os.path.dirname(HERE)
FILES = ('livecode/contract_aliases.livecodescript', 'Data/contract_words.txt', 'Data/Menus/Contract.txt')


def plain(text):
    """A table cell as plain words: no code marks, no bold, one line, no tabs."""
    text = text.replace('\\|', '|').replace('`', '').replace('**', '')
    return re.sub(r'\s+', ' ', text).strip()


def shape(form):
    """(name, 'function' or 'command', [parameter names]) from a row's first `code`."""
    form = form.strip()
    m = re.match(r'([A-Za-z_][\w.]*)\s*\((.*)\)\s*$', form)
    if m:
        kind, rest = 'function', m.group(2)
    else:
        m = re.match(r'([A-Za-z_][\w.]*)\s*(.*)$', form)
        kind, rest = 'command', m.group(2)
    params = [p.strip() for p in rest.split(',') if re.fullmatch(r'\s*[A-Za-z_]\w*\s*', p)]
    return m.group(1), kind, params


def rows_of(contract):
    """The contract's rows, one for each name (a name listed twice: the first row counts)."""
    seen, rows = set(), []
    for r in contract.rows:
        key = (r['kind'], r['name'].lower())
        if key not in seen:
            seen.add(key)
            rows.append(r)
    return rows


def aliases_text(contract):
    new_rows = {r['name'].lower(): r for r in rows_of(contract) if r['kind'] == 'call'}
    out = ['-- GENERATED by LIB_ig3d/tools/make_names.py from ENGINE_CONTRACT.md (section 16): do not edit.',
           '-- Rename Day: each new Group.Verb name passes straight to the engine handler that still has',
           '-- the old name. No `script` line on purpose: this file is appended to the engine',
           '-- (xt3d tools/make_vibe_xt3d.py) and added after the stand-ins in headless tests.',
           '']
    problems = []
    for old, (old_name, new_name, how) in contract.renames.items():
        row = new_rows.get(new_name.lower())
        if row is None:
            problems.append('renames: %s has no row in the call tables' % new_name)
            continue
        if not row['xt'].startswith('yes'):
            continue                       # a planned call has nothing to pass to yet
        name, kind, params = shape(row['form'])
        plist = ', '.join(params)
        out.append('%s %s%s' % ('function' if kind == 'function' else 'on', name, ' ' + plist if plist else ''))
        if how == 'signs':
            out.append('   -- the old call took these numbers with their signs turned round; empty stays empty')
            for p in params:
                out.append('   if %s is a number then put 0 - %s into %s' % (p, p, p))
        elif how != 'same':
            problems.append('renames: %s: the alias must be `same` or `signs`, not %r' % (old_name, how))
        if kind == 'function':
            out.append('   return %s(%s)' % (old_name, plist))
        else:
            out.append('   %s%s' % (old_name, ' ' + plist if plist else ''))
            out.append('   return the result')
        out.append('end %s' % name)
        out.append('')
    return '\n'.join(out).rstrip('\n') + '\n', problems


def words_text(contract):
    old_of = {new.lower(): old for old, new, how in contract.renames.values()}
    out = ['# GENERATED by LIB_ig3d/tools/make_names.py from ENGINE_CONTRACT.md: do not edit.',
           '# kind, group, name, form, gives (yes: it gives a value back), xt (yes / planned), old name,',
           '# first parameter, meaning. Tabs between. Read by LIB_ig3d/livecode/lib_suggest.livecodescript.']
    for r in rows_of(contract):
        name, kind, params = shape(r['form'])
        if r['kind'] == 'value':
            group, gives, form = 'Value', 'yes', name
        else:
            group = name.split('.')[0] if '.' in name else ''
            gives = 'yes' if kind == 'function' else 'no'
            form = name + ('(' + ', '.join(params) + ')' if kind == 'function' else
                           (' ' + ', '.join(params) if params else ''))
        xt = 'yes' if r['xt'].startswith('yes') else 'planned'
        out.append('\t'.join([r['kind'], group, name, form, gives, xt, old_of.get(name.lower(), ''),
                              params[0] if params else '', plain(r['meaning'])]))
    return '\n'.join(out) + '\n'


def menu_text(contract):
    out = ['# GENERATED by LIB_ig3d/tools/make_names.py from ENGINE_CONTRACT.md: do not edit.',
           '# The Contract menu: every call a game may make, by group. One menu = one file (LIB_MENU);',
           '# lines are paths, Head/Sub/Item. A pick goes to one handler with the whole path',
           '# ("Contract/Entity/Entity.SetPosition"); Suggest.Pick gives the text to paste.',
           'handler: ContractMenuPick']
    for r in rows_of(contract):
        if r['kind'] != 'call':
            continue
        name = shape(r['form'])[0]
        group = name.split('.')[0] if '.' in name else 'Other'
        out.append('Contract/%s/%s' % (group, name))
    # keep each group's lines together, groups in the order they first appear
    head, items = out[:5], out[5:]
    order = []
    for line in items:
        g = line.split('/')[1]
        if g not in order:
            order.append(g)
    items = [l for g in order for l in items if l.split('/')[1] == g]
    return '\n'.join(head + items) + '\n'


def build(contract):
    aliases, problems = aliases_text(contract)
    return {FILES[0]: aliases, FILES[1]: words_text(contract), FILES[2]: menu_text(contract)}, problems


def main(argv):
    check, contract_path, out = False, cc.CONTRACT, LIB
    it = iter(argv)
    for a in it:
        if a == '--check':
            check = True
        elif a == '--contract':
            contract_path = next(it)
        elif a == '--out':
            out = os.path.abspath(next(it))
        elif a in ('-h', '--help'):
            print(__doc__)
            return 0
    contract = cc.Contract(cc.read(contract_path))
    files, problems = build(contract)
    for p in problems:
        print('WRONG ' + p)
    stale = 0
    for rel, text in files.items():
        path = os.path.join(out, rel)
        if check:
            same = os.path.exists(path) and cc.read(path) == text
            print('%s %s' % ('ok   ' if same else 'STALE', rel))
            stale += 0 if same else 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('wrote', rel)
    if check and stale:
        print('run: python3 -I LIB_ig3d/tools/make_names.py')
    return 1 if (problems or stale) else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
